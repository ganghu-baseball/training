// ───────── 反向跳（先蹲馬上跳）vs 蹲踞跳（蹲著停 3 秒再跳）─────────
export function makeJump(o = {}) {
  const counter = o.counter !== false;
  const c = {};
  // 面向鏡頭（+Z）
  const t0 = o.start ?? 0.8;
  let dip, bottom, take, peak, land, absorb, stand, h;
  if (counter) { dip = t0; bottom = t0 + 0.42; take = bottom + 0.26; h = 0.44; }
  else { dip = t0; bottom = t0 + 0.7; take = bottom + 3.0 + 0.3; h = 0.36; }
  const flight = 2 * Math.sqrt(2 * h / 9.8);
  peak = take + flight / 2; land = take + flight; absorb = land + 0.22; stand = absorb + 0.6;
  const yStand = 0.97, yLow = 0.72, yTake = 1.06;
  const py = [[0, yStand - 0.02], [dip, yStand - 0.02], [bottom, yLow]];
  if (!counter) py.push([take - 0.3, yLow]);
  py.push([take, yTake]);
  // 空中：拋物線
  const N = 8;
  for (let i = 1; i < N; i++) { const s = i / N; const tt = take + s * flight; py.push([tt, yTake + 4 * h * s * (1 - s)]); }
  py.push([land, yTake], [absorb, 0.78], [stand, yStand - 0.02], [stand + 2, yStand - 0.02]);
  c['pel.y'] = py;
  c['pel.x'] = K([0, 0], [20, 0]); c['pel.z'] = K([0, 0.0], [bottom, -0.07], [take, 0.0], [absorb, -0.05], [stand, 0], [stand + 2, 0]);
  c['pel.yaw'] = K([0, -90], [20, -90]);
  const tl = [[0, 4], [dip, 4], [bottom, 32]]; if (!counter) tl.push([take - 0.3, 32]); tl.push([take, 2], [land, 4], [absorb, 26], [stand, 4], [stand + 2, 4]);
  c['pel.tilt'] = tl;
  c['tr.flex'] = K([0, 3], [20, 3]);
  // 腳：起跳時腳尖點地 → 離地
  const fy = [[0, 0], [take - 0.06, 0]];
  for (let i = 1; i < N; i++) { const s = i / N; fy.push([take + s * flight, Math.max(0, 4 * h * s * (1 - s) + 0.02)]); }
  fy.push([land, 0], [stand + 2, 0]);
  const fp = [[0, 0], [take - 0.12, 0], [take, 40], [take + flight * 0.5, 25], [land - 0.04, 12], [land, 0], [stand + 2, 0]];
  for (const [side, x] of [['r', -0.15], ['l', 0.15]]) {
    c[side + 'f.x'] = K([0, x], [20, x]); c[side + 'f.z'] = K([0, 0.10], [20, 0.10]);
    c[side + 'f.yaw'] = K([0, side === 'r' ? -96 : -84], [20, side === 'r' ? -96 : -84]);
    c[side + 'f.y'] = fy; c[side + 'f.pitch'] = fp;
  }
  // 手臂擺動：下蹲時往後、起跳時往上
  const abd = [[0, 12], [dip, 12], [bottom, 30]]; if (!counter) abd.push([take - 0.3, 30]); abd.push([take, 150], [peak, 160], [land, 60], [absorb, 30], [stand, 12], [stand + 2, 12]);
  const hz = [[0, 80], [dip, 80], [bottom, -50]]; if (!counter) hz.push([take - 0.3, -50]); hz.push([take, 90], [peak, 90], [land, 85], [stand, 80], [stand + 2, 80]);
  const ef = [[0, 15], [dip, 15], [bottom, 10]]; if (!counter) ef.push([take - 0.3, 10]); ef.push([take, 20], [land, 25], [stand, 15], [stand + 2, 15]);
  for (const s of ['ra', 'la']) { c[s + '.abd'] = abd; c[s + '.hz'] = hz; c[s + '.ef'] = ef; c[s + '.er'] = K([0, 0], [20, 0]); }
  return new Motion(c, { props: { kind: 'jump', ground: FLAT, look: [0, 1.5, 12] }, events: { dip, bottom, take, peak, land, h } });
}
