// 雙手在準備姿勢時握在胸前：用 IK 求出角度再放入通道
const ARM_SET = {
  r: { t: [0.20, -0.36, 0.03], pole: [-0.2, -1, 1] },
  l: { t: [0.18, -0.30, -0.13], pole: [-0.2, -1, -1] },
};
const ARM_FIELD = {
  r: { t: [0.34, -0.44, 0.10], pole: [-0.1, -1, 1] },
  l: { t: [0.36, -0.40, -0.10], pole: [-0.1, -1, -1] },
};

function localToWorld(S, [f, u, r]) {
  return S.P3.clone().add(S.F.clone().multiplyScalar(f)).add(S.U.clone().multiplyScalar(u)).add(S.R.clone().multiplyScalar(r));
}
function localDir(S, [f, u, r]) {
  return S.F.clone().multiplyScalar(f).add(S.U.clone().multiplyScalar(u)).add(S.R.clone().multiplyScalar(r)).normalize();
}

export function addIkArmKeys(channels, keys) {
  // keys: [{t, side:'r'|'l', target:[f,u,r], pole:[f,u,r]}]
  const tmp = new Motion(channels);
  for (const k of keys) {
    const pose = poseAt(tmp, k.t);
    const S = solveSkeleton(pose);
    const ang = armAnglesFromTarget(S, k.side === 'r' ? 1 : -1, localToWorld(S, k.target), localDir(S, k.pole));
    const pre = k.side === 'r' ? 'ra.' : 'la.';
    for (const n of ['abd', 'hz', 'er', 'ef']) channels[pre + n] = setKey(channels[pre + n] || [], k.t, ang[n]);
    if (k.pro !== undefined) channels[pre + 'pro'] = setKey(channels[pre + 'pro'] || [], k.t, k.pro);
  }
}

export function makePitch(opt = {}) {
  const c = pitchChannels(opt);
  const off = opt.noDrift ? 0.45 : 0;
  const ikKeys = [];
  for (const t of [-3, -1.30, -0.62 + (opt.noDrift ? 0 : 0), -0.52 + off]) {
    ikKeys.push({ t, side: 'r', target: ARM_SET.r.t, pole: ARM_SET.r.pole });
    ikKeys.push({ t, side: 'l', target: ARM_SET.l.t, pole: ARM_SET.l.pole });
  }
  const GLOVE = [
    [-0.40, [0.25, -0.30, -0.35], [-0.3, -1, -0.5]], [-0.25, [0.12, -0.10, -0.60], [0, -1, -0.2]],
    [-0.10, [0.08, -0.04, -0.70], [-0.1, -1, 0.1]], [0.0, [0.08, -0.03, -0.72], [-0.2, -1, 0]],
    [0.05, [0.17, -0.08, -0.64], [-0.4, -1, 0]], [0.10, [0.30, -0.16, -0.46], [-0.4, -1, -0.3]],
    [0.145, [0.30, -0.24, -0.27], [-0.3, -1, -0.8]], [0.25, [0.27, -0.30, -0.20], [-0.2, -1, -0.8]],
    [0.50, [0.30, -0.36, -0.13], [-0.1, -1, -0.6]], [0.85, [0.34, -0.37, -0.09], [-0.1, -1, -0.6]],
  ];
  for (const [t, target, pole] of GLOVE) ikKeys.push({ t: t + off, side: 'l', target, pole });
  ikKeys.push({ t: 1.15 + off, side: 'r', target: ARM_FIELD.r.t, pole: ARM_FIELD.r.pole, pro: 0 });
  ikKeys.push({ t: 1.15 + off, side: 'l', target: ARM_FIELD.l.t, pole: ARM_FIELD.l.pole, pro: 0 });
  addIkArmKeys(c, ikKeys);
  const br = EV.BR + off + (opt.lateArm ? 0.01 : 0);
  return new Motion(c, { events: { ...EV, BR: br, FC: off, MER: EV.MER + off, PKH: EV.PKH }, props: { kind: 'pitch', release: br } });
}

