const K = (...pairs) => pairs;           // 可讀性用
function shiftKeys(keys, from, dt) { return keys.map(([t, v]) => [t >= from ? t + dt : t, v]); }
function setKey(keys, t, v) {
  const out = keys.filter(k => Math.abs(k[0] - t) > 1e-6); out.push([t, v]); return out.sort((a, b) => a[0] - b[0]);
}
function scaleBetween(keys, t0, t1, fn) { return keys.map(([t, v]) => (t >= t0 && t <= t1) ? [t, fn(v, t)] : [t, v]); }

